"""Пропозиція відкату щойно виконаної дії ("Повернути" у тості).

Дія, яку можна повернути, не питає підтвердження: вона виконується одразу,
а адмін отримує тост із кнопкою відкату. Це дешевше за діалог -- підтвердження
коштує клік завжди, відкат -- лише коли справді помилились.

Пропозиція живе рівно один редірект: роут кладе її у сесію, наступний рендер
забирає і віддає шаблону. Замість flash(): інакше та сама подія показалась би
двома тостами.

Умова застосування: відкат мусить бути ПОВНИМ. Якщо дія має побічні ефекти,
яких restore не поверне (напр. видалення медіа чистить посилання на нього в
контенті блогу), пропонувати undo не можна -- там лишається діалог.
"""
from flask import session

_KEY = 'undo_offer'


def offer_undo(message, restore_url, label='Повернути'):
    """Показати тост із кнопкою відкату замість звичайного flash."""
    session[_KEY] = {
        'message': message,
        'url': restore_url,
        'label': label,
    }


def pop_undo():
    """Забрати пропозицію (одноразова)."""
    return session.pop(_KEY, None)
