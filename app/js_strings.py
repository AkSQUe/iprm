"""Рядки публічних JS-файлів для i18n.

JS не має доступу до gettext, тому всі видимі користувачу українські рядки
з app/static/js/*.js зібрано тут. `_` нижче -- no-op маркер для
pybabel-екстракції (той самий патерн, що в app/models/specializations.py):
рядок потрапляє в .pot-каталог, а значення в списку лишається незмінним.

Runtime: js_translations() повертає dict {укр. рядок: переклад для поточної
локалі}. Він серіалізується в base.html у <script type="application/json"
id="iprm-i18n-data"> і читається app/static/js/i18n.js
(window.iprmI18n.t(key, params)).

Плейсхолдери вигляду {name} підставляються на боці JS (i18n.js), тому в
перекладах їх треба зберігати як є.

При додаванні нового t('...') у публічний JS рядок ОБОВ'ЯЗКОВО додати сюди,
інакше він не перекладатиметься.
"""


